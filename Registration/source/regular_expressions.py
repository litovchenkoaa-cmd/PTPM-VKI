import re

# Логин: телефон (+x-xxx-xxx-xxxx) ИЛИ email ИЛИ строка (мин 5 символов, латиница, цифры, _)
login_re = re.compile(
    r"^(?:"
    r"\+\d-\d{3}-\d{3}-\d{4}"                                  # Телефон: +7-999-999-9999
    r"|[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)*@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}"  # Email
    r"|[A-Za-z0-9_]{5,}"                                        # Строка: мин 5 символов
    r")$"
)